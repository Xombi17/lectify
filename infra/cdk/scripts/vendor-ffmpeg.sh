#!/usr/bin/env bash
# Vendor ffmpeg static build for AL2023 EC2 worker instances.
# Downloads the pinned static build to infra/cdk/bootstrap/vendor/, computes sha256,
# and writes infra/cdk/bootstrap/ffmpeg.sha256 in sha256sum -c format.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CDK_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
VENDOR_DIR="${CDK_DIR}/bootstrap/vendor"
ARCHIVE_NAME="ffmpeg-release-amd64-static.tar.xz"
DEST_ARCHIVE="${VENDOR_DIR}/${ARCHIVE_NAME}"
CHECKSUM_FILE="${CDK_DIR}/bootstrap/ffmpeg.sha256"

# Pinned release configuration
FFMPEG_VERSION="release-amd64-static"
FFMPEG_URL="https://johnvansickle.com/ffmpeg/releases/ffmpeg-release-amd64-static.tar.xz"

mkdir -p "${VENDOR_DIR}"

if [[ -f "${DEST_ARCHIVE}" ]] && [[ -f "${CHECKSUM_FILE}" ]]; then
  # Check if existing archive matches checksum
  if (cd "${VENDOR_DIR}" && sha256sum -c "${CHECKSUM_FILE}" >/dev/null 2>&1); then
    echo "ffmpeg archive already present and checksum matches; nothing to do."
    exit 0
  fi
fi

echo "Downloading ffmpeg from ${FFMPEG_URL}..."
TMP_ARCHIVE="${DEST_ARCHIVE}.tmp.$$"
curl -fsSL "${FFMPEG_URL}" -o "${TMP_ARCHIVE}"
mv "${TMP_ARCHIVE}" "${DEST_ARCHIVE}"

# Compute sha256 and write in sha256sum -c format
echo "Computing SHA-256 checksum..."
ACTUAL_SHA256="$(sha256sum "${DEST_ARCHIVE}" | awk '{print $1}')"

cat > "${CHECKSUM_FILE}" <<EOF
# Pinned ffmpeg checksum generated by scripts/vendor-ffmpeg.sh
# Version: ${FFMPEG_VERSION}
# URL: ${FFMPEG_URL}
# Note: Trust-On-First-Use (TOFU). Verified during EC2 instance bootstrap.
${ACTUAL_SHA256}  ${ARCHIVE_NAME}
EOF

echo "Wrote checksum to ${CHECKSUM_FILE}:"
cat "${CHECKSUM_FILE}"
echo ""
echo "NOTICE (TOFU): The static ffmpeg binary has been vendored."
echo "The SHA-256 hash has been pinned in ${CHECKSUM_FILE} and will be checked"
echo "by worker EC2 instances before extraction."
